// Original schematic layout of the Lands Between — not traced or copied
// from any existing map image (in-game or fan-made).
//
// Every surface region now carries a `shapePoints` override: an explicit
// silhouette, as fractions of the region's own bounding box (x/y/width/
// height below), used instead of the generic jittered-rect silhouette in
// render.ts's fallback path. These were hand-molded by the user directly
// in the Shape Editor tab (drag/add/remove vertices), not generated or
// guessed by Claude — Claude's role was reviewing reference images for
// proportion/orientation only earlier in this project, never tracing or
// digitizing them. Several regions' points now range well outside their
// own [0,1] bounding box (some past 2.0) — that's intentional: the user
// dragged region edges out to meet their neighbors, closing the gaps that
// made the schematic read as separate floating islands rather than one
// connected landmass. Because of that, x/y/width/height below are no
// longer just "this region's area" — they're the coordinate anchor the
// shapePoints fractions are measured from, and other regions' shapes now
// extend into this region's nominal box (and vice versa). Don't resize a
// region's box without re-deriving its neighbors' shapePoints too.
export interface Region {
  id: string;
  name: string;
  x: number;
  y: number;
  width: number;
  height: number;
  color: string;
  shapePoints?: [number, number][];
  // Region-name label anchor, fraction space — defaults to the shape
  // polygon's centroid when absent (computed once below; underground
  // regions don't need this since they never got shapePoints molding).
  labelPos?: [number, number];
}

